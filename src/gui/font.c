void draw_char(uint32_t *buffer, int pitch_pixels, int x, int y, char c, uint32_t fg, uint32_t bg, int transparent_bg) {
    unsigned char uc = (unsigned char)c;
    for (int row = 0; row < FONT_HEIGHT; row++) {
        uint8_t bits = aweos_font8x16[uc][row];
        for (int col = 0; col < FONT_WIDTH; col++) {
            int px = x + col;
            int py = y + row;
            if (px < 0 || py < 0) continue;
            if (bits & (0x80 >> col)) {
                buffer[py * pitch_pixels + px] = fg;
            } else if (!transparent_bg) {
                buffer[py * pitch_pixels + px] = bg;
            }
        }
    }
}

void draw_string(uint32_t *buffer, int pitch_pixels, int x, int y, const char *str, uint32_t fg, uint32_t bg, int transparent_bg) {
    int cur_x = x;
    while (*str) {
        draw_char(buffer, pitch_pixels, cur_x, y, *str, fg, bg, transparent_bg);
        cur_x += FONT_WIDTH;
        str++;
    }
}

void draw_string_clipped(uint32_t *buffer, int pitch_pixels, int x, int y, const char *str, uint32_t fg, int max_width) {
    int cur_x = x;
    while (*str && (cur_x + FONT_WIDTH <= x + max_width)) {
        draw_char(buffer, pitch_pixels, cur_x, y, *str, fg, 0, 1);
        cur_x += FONT_WIDTH;
        str++;
    }
}

int string_width(const char *str) {
    if (!str) return 0;
    return strlen(str) * FONT_WIDTH;
}
